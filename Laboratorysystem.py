class DatabaseCursor:
    """Small compatibility wrapper so existing SQLite ? placeholders still work on PostgreSQL."""
    def __init__(self, cursor, postgres=False):
        self._cursor = cursor
        self._postgres = postgres

    def execute(self, sql, params=None):
        if self._postgres:
            sql = sql.replace("?", "%s")
        return self._cursor.execute(sql, params) if params is not None else self._cursor.execute(sql)

    def executemany(self, sql, seq_of_params):
        if self._postgres:
            sql = sql.replace("?", "%s")
        return self._cursor.executemany(sql, seq_of_params)

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __getattr__(self, name):
        """Expose standard cursor attributes such as rowcount to existing code."""
        return getattr(self._cursor, name)


class DatabaseConnection:
    def __init__(self, connection, postgres=False):
        self._connection = connection
        self._postgres = postgres

    def cursor(self):
        return DatabaseCursor(self._connection.cursor(), self._postgres)

    def commit(self):
        return self._connection.commit()

    def close(self):
        return self._connection.close()


def get_db_connection():
    """Return Supabase PostgreSQL when DATABASE_URL is set; otherwise the original SQLite database."""
    database_url = os.getenv("DATABASE_URL")
    if database_url:
        if psycopg is None:
            raise RuntimeError("psycopg is required when DATABASE_URL is set. Install requirements.txt.")
        return DatabaseConnection(psycopg.connect(database_url), postgres=True)
    return DatabaseConnection(sqlite3.connect(DB_NAME), postgres=False)


